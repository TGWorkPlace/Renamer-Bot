@Client.on_message(filters.command("users") & filters.user(Config.ADMIN))
async def get_users_list(bot: Client, message: Message):
    """Get list of all users with their mention and user ID"""
    status_msg = await message.reply('**Fᴇᴛᴄʜɪɴɢ Uꜱᴇʀꜱ Lɪꜱᴛ...**')
    
    try:
        all_users = await db.get_all_users()
        total_users = await db.total_users_count()
        
        if total_users == 0:
            return await status_msg.edit("**Nᴏ Uꜱᴇʀꜱ Fᴏᴜɴᴅ!**")
        
        users_list = "**📋 Aʟʟ Uꜱᴇʀꜱ Lɪꜱᴛ:**\n\n"
        count = 0
        user_details = []
        
        async for user in all_users:
            user_id = user['_id']
            count += 1
            
            try:
                # Try to get user details from Telegram
                user_info = await bot.get_users(user_id)
                mention = user_info.mention
                user_details.append(f"{count}. {mention} : `{user_id}`")
            except Exception as e:
                # If user cannot be fetched, just show ID
                user_details.append(f"{count}. User : `{user_id}`")
            
            # Send message in chunks of 50 users to avoid message length limit
            if count % 50 == 0:
                chunk_message = users_list + "\n".join(user_details)
                chunk_message += f"\n\n**Sʜᴏᴡɪɴɢ {count}/{total_users} Uꜱᴇʀꜱ**"
                await message.reply(chunk_message)
                user_details = []
        
        # Send remaining users
        if user_details:
            final_message = users_list + "\n".join(user_details)
            final_message += f"\n\n**Tᴏᴛᴀʟ Uꜱᴇʀꜱ: {total_users}**"
            await message.reply(final_message)
        
        await status_msg.delete()
        
    except Exception as e:
        logger.error(f"Error in get_users_list: {e}")
        await status_msg.edit(f"**Eʀʀᴏʀ:** `{str(e)}`")


